def _drop_tables(conn): 
    with conn.cursor() as cursor:
        cursor.execute("CREATE EXTENSION IF NOT EXISTS postgis;")
        cursor.execute("""
        DROP TABLE IF EXISTS vehicle_assignment CASCADE;
        DROP TABLE IF EXISTS driver CASCADE;
        DROP TABLE IF EXISTS trip CASCADE;
        DROP TABLE IF EXISTS location_ping CASCADE;
        DROP TABLE IF EXISTS parking_area CASCADE;
        DROP TABLE IF EXISTS road_segment CASCADE;
        DROP TABLE IF EXISTS vehicle CASCADE;
        DROP TABLE IF EXISTS vehicle_type CASCADE;
        DROP TABLE IF EXISTS vehicle_status CASCADE;
        DROP TABLE IF EXISTS vehicle_kind CASCADE;
        DROP TABLE IF EXISTS fuel_type CASCADE;
        DROP TABLE IF EXISTS login CASCADE;
        """)

def _create_tables(conn): 
    with conn.cursor() as cursor:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS fuel_type (
                fuel_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS vehicle_kind (
                vehicle_kind_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS vehicle_status (
                vehicle_status_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS vehicle_type (
                vehicle_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                vehicle_kind_id INTEGER NOT NULL REFERENCES vehicle_kind(vehicle_kind_id),
                fuel_type_id INTEGER NOT NULL REFERENCES fuel_type(fuel_type_id),
                emissions_rating DOUBLE PRECISION,
                created_at TIMESTAMP NOT NULL
            );

            CREATE TABLE IF NOT EXISTS vehicle (
                vehicle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                vehicle_type_id BIGINT NOT NULL REFERENCES vehicle_type(vehicle_type_id),
                vehicle_status_id INTEGER NOT NULL REFERENCES vehicle_status(vehicle_status_id),
                plate_number TEXT NOT NULL,
                make TEXT NOT NULL,
                model TEXT NOT NULL,
                year INTEGER NOT NULL,
                created_at TIMESTAMP NOT NULL
            );

            CREATE TABLE IF NOT EXISTS road_segment (
                road_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                speed_limit_kph INTEGER NOT NULL,
                geom geometry(LINESTRING, 4326) NOT NULL,
                created_at TIMESTAMP NOT NULL,
                is_oneway BOOLEAN NOT NULL,
                direction TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS parking_area (
                parking_area_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                capacity INTEGER NOT NULL,
                geom geometry(POLYGON, 4326) NOT NULL,
                created_at TIMESTAMP NOT NULL
            );

            CREATE TABLE IF NOT EXISTS location_ping (
                ping_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                vehicle_id BIGINT NOT NULL REFERENCES vehicle(vehicle_id),
                ts TIMESTAMP NOT NULL,
                geom geometry(POINT, 4326) NOT NULL,
                speed_kph DOUBLE PRECISION,
                heading_deg DOUBLE PRECISION
            );

            CREATE TABLE IF NOT EXISTS trip (
                trip_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                vehicle_id BIGINT NOT NULL REFERENCES vehicle(vehicle_id),
                start_ts TIMESTAMP NOT NULL,
                end_ts TIMESTAMP NOT NULL,
                start_geom geometry(POINT, 4326) NOT NULL,
                end_geom geometry(POINT, 4326) NOT NULL,
                distance_km DOUBLE PRECISION NOT NULL
            );
                       
            CREATE TABLE IF NOT EXISTS driver (
                driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                first_name TEXT,
                last_name TEXT,
                license_number TEXT,
                hired_at TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS vehicle_assignment (
                assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                vehicle_id BIGINT REFERENCES vehicle(vehicle_id),
                driver_id BIGINT REFERENCES driver(driver_id),
                assigned_from TIMESTAMP,
                assigned_to TIMESTAMP
            );
        
            CREATE TABLE IF NOT EXISTS login (
                user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL
            );
        """)

def sync_identity_sequences(conn):
    with conn.cursor() as cursor:
        cursor.execute("""
            SELECT setval(pg_get_serial_sequence('vehicle_type', 'vehicle_type_id'),
                          COALESCE((SELECT MAX(vehicle_type_id) FROM vehicle_type), 1), true);
            SELECT setval(pg_get_serial_sequence('driver', 'driver_id'),
                          COALESCE((SELECT MAX(driver_id) FROM driver), 1), true);
            SELECT setval(pg_get_serial_sequence('vehicle_assignment', 'assignment_id'),
                          COALESCE((SELECT MAX(assignment_id) FROM vehicle_assignment), 1), true);
            SELECT setval(pg_get_serial_sequence('vehicle', 'vehicle_id'),
                          COALESCE((SELECT MAX(vehicle_id) FROM vehicle), 1), true);

            SELECT setval(pg_get_serial_sequence('road_segment', 'road_id'),
                          COALESCE((SELECT MAX(road_id) FROM road_segment), 1), true);

            SELECT setval(pg_get_serial_sequence('parking_area', 'parking_area_id'),
                          COALESCE((SELECT MAX(parking_area_id) FROM parking_area), 1), true);

            SELECT setval(pg_get_serial_sequence('location_ping', 'ping_id'),
                          COALESCE((SELECT MAX(ping_id) FROM location_ping), 1), true);

            SELECT setval(pg_get_serial_sequence('trip', 'trip_id'),
                          COALESCE((SELECT MAX(trip_id) FROM trip), 1), true);
        """)

def reset_schema(conn):
    _drop_tables(conn)
    _create_tables(conn)